import 'dart:async';
import 'dart:convert';

import 'package:http/http.dart' as http;
import 'package:ingrain/features/content/data/youtube_transcript_fetcher.dart';

/// Key for the official YouTube Data API v3, passed at build time with
/// `--dart-define=YOUTUBE_API_KEY=...`. Empty leaves the API out.
///
/// Restrict the key to the "YouTube Data API v3" in the Cloud console rather
/// than to the Android app: these calls go through `http`, which does not send
/// the package and certificate headers an app restriction checks.
const youtubeDataApiKey = String.fromEnvironment('YOUTUBE_API_KEY');

/// A caption track as the official API lists it.
class OfficialCaptionTrack {
  final String language;

  /// YouTube's speech recognition made it (`trackKind: asr`).
  final bool isAutoGenerated;

  const OfficialCaptionTrack({
    required this.language,
    required this.isAutoGenerated,
  });
}

/// Which caption tracks a video has, from the official YouTube Data API.
///
/// The official API can only *list* tracks for other people's videos:
/// `captions.download` needs OAuth from the video's owner. So this does not
/// fetch transcript text. It settles whether a video has Japanese captions at
/// all once the unofficial fetchers have failed, so the learner hears "no
/// subtitles" or "try again later" instead of a guess. Each call costs 50 of
/// the default 10,000 daily quota units.
class YoutubeDataApiCaptions {
  final http.Client _client;
  final String _apiKey;

  YoutubeDataApiCaptions({
    http.Client? client,
    this._apiKey = youtubeDataApiKey,
  }) : _client = client ?? http.Client();

  bool get isConfigured => _apiKey.isNotEmpty;

  void close() => _client.close();

  /// The video's Japanese track (hand-made preferred), or null when it has
  /// none or the video does not exist.
  Future<OfficialCaptionTrack?> japaneseTrack(String videoId) async {
    final uri = Uri.https('www.googleapis.com', '/youtube/v3/captions', {
      'part': 'snippet',
      'videoId': videoId,
      'key': _apiKey,
    });
    final http.Response response;
    try {
      response = await _client.get(uri).timeout(const Duration(seconds: 10));
    } on TimeoutException {
      throw const YoutubeTranscriptException(
        'The YouTube Data API took too long to answer.',
      );
    } catch (error) {
      throw YoutubeTranscriptException('Could not reach YouTube: $error');
    }

    if (response.statusCode == 404) return null;
    if (response.statusCode != 200) {
      throw YoutubeTranscriptException(
        'YouTube Data API error ${response.statusCode}: ${_reason(response)}',
      );
    }

    final items = (jsonDecode(response.body) as Map)['items'] as List? ?? [];
    final tracks = [
      for (final item in items.cast<Map>())
        if (item['snippet'] case final Map snippet)
          OfficialCaptionTrack(
            language: snippet['language'] as String? ?? '',
            isAutoGenerated: snippet['trackKind'] == 'asr',
          ),
    ];
    return YoutubeTranscriptFetcher.pickJapaneseTrack(
      tracks,
      languageCode: (t) => t.language,
      isAutoGenerated: (t) => t.isAutoGenerated,
    );
  }

  static String _reason(http.Response response) {
    try {
      final error = (jsonDecode(response.body) as Map)['error'] as Map;
      return error['message'] as String? ?? response.reasonPhrase ?? '';
    } catch (_) {
      return response.reasonPhrase ?? '';
    }
  }
}
